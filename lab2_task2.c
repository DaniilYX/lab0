#include <stdio.h>
int main()
{
    int N = 19;
    int K = 20;
    printf("Сейчас %d часов %d минут 00 секунд\n", N, K);
    printf("Идет %d минута суток\n", (N * 60) + K);
    printf("До полуночи осталось %d часов и %d минут\n", 24 - N, 1440 - K);
    printf("С 8.00 прошло %d секунд\n", (N - 8) * 3600 + (K * 60));
    printf("Текущий час  = %.2f суток и текущая минута = %.2f часа\n", N / 24.0, K / 60.0);
}